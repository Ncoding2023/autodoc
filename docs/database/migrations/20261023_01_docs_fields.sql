-- DOCS 양식 항목 정의와 문서별 입력값. 기존 문서·시트 데이터는 변경하지 않는다.
-- 실행 전 기존 스키마가 준비되어 있어야 한다. 외래 키 제약조건은 사용하지 않는다.
BEGIN;

CREATE TABLE IF NOT EXISTS template_fields (
    template_field_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_id BIGINT NOT NULL,
    field_key VARCHAR(100) NOT NULL,
    field_label VARCHAR(100) NOT NULL,
    field_type VARCHAR(20) NOT NULL,
    field_order INTEGER NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_template_fields_template_key UNIQUE (template_id, field_key),
    CONSTRAINT uk_template_fields_template_order UNIQUE (template_id, field_order),
    CONSTRAINT ck_template_fields_type CHECK (field_type IN ('TEXT', 'LONG_TEXT', 'DATE')),
    CONSTRAINT ck_template_fields_order CHECK (field_order > 0),
    CONSTRAINT ck_template_fields_key CHECK (field_key ~ '^[A-Za-z가-힣][A-Za-z0-9가-힣_]{0,99}$'),
    CONSTRAINT ck_template_fields_label CHECK (length(btrim(field_label)) > 0)
);

CREATE TABLE IF NOT EXISTS document_fields (
    document_field_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL,
    field_key VARCHAR(100) NOT NULL,
    field_label VARCHAR(100) NOT NULL,
    field_type VARCHAR(20) NOT NULL,
    field_order INTEGER NOT NULL,
    field_value TEXT,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_document_fields_document_key UNIQUE (document_id, field_key),
    CONSTRAINT uk_document_fields_document_order UNIQUE (document_id, field_order),
    CONSTRAINT ck_document_fields_type CHECK (field_type IN ('TEXT', 'LONG_TEXT', 'DATE')),
    CONSTRAINT ck_document_fields_order CHECK (field_order > 0),
    CONSTRAINT ck_document_fields_key CHECK (field_key ~ '^[A-Za-z가-힣][A-Za-z0-9가-힣_]{0,99}$'),
    CONSTRAINT ck_document_fields_label CHECK (length(btrim(field_label)) > 0)
);

ALTER TABLE documents ADD COLUMN IF NOT EXISTS source_template_file_id BIGINT;
COMMENT ON COLUMN documents.source_template_file_id IS 'DOCS 작성 시작 시 사용한 원본 양식 파일 ID. 기존 문서는 NULL';
COMMENT ON TABLE template_fields IS 'DOCS 템플릿의 입력 항목 정의. field_key는 이름 변경과 무관한 연결 키';
COMMENT ON TABLE document_fields IS 'DOCS 문서별 항목 정의 사본과 입력값. 다른 문서나 템플릿의 변경과 분리';

COMMIT;
